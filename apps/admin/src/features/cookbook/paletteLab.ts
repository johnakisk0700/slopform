/**
 * The cookbook's palette lab: complete, pre-checked candidate palettes an
 * operator can throw over the live tokens to audition a different field.
 *
 * Each candidate is a FLAT map of every semantic colour token, per theme —
 * resolved hexes, no var() chains — so applying one is nothing but inline
 * custom properties on <html>, and removing it restores tokens.css exactly.
 * The `dark` class stays the only theme signal: a candidate carries both
 * themes and the consumer re-applies the matching half when the class flips.
 *
 * This file is data, like tokens.css: the one place outside the token source
 * where literal colours are allowed. Every candidate passes the same 12 AA
 * pairs `theme-tokens.spec.ts` asserts, in both themes — `palette-lab.spec.ts`
 * recomputes them — so no candidate can audition an inaccessible panel.
 *
 * Dev-only by construction: only the cookbook page imports it, and the
 * cookbook chunk never reaches a production build.
 */

