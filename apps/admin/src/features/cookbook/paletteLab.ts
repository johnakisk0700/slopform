/**
 * The inline overrides to paint for a selection, or null for "current tokens".
 * Pure so the spec can exercise it without a DOM.
 */
export function paletteLabOverrides(
  candidateId: string | null,
  isDark: boolean,
): Record<PaletteLabToken, string> | null {
  if (candidateId === null) return null;
  const candidate = PALETTE_CANDIDATES.find((c) => c.id === candidateId);
  if (!candidate) return null;
  return candidate.tokens[isDark ? "dark" : "light"];
}
